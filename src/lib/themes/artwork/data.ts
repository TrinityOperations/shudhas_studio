import type { ThemeId } from "@/lib/themes/themes";
import type { SeasonIconName } from "./icons";

/**
 * Per-theme artwork layouts (docs/design.md, "Seasonal artwork"), generated once from the approved
 * mock-up. Positions are percentages of the box they sit in (the header row, the tag, the footer);
 * sizes are pixels; colours are the theme's `deco` or ivory. Themes themselves (`themes.ts`)
 * stay about colour and copy; everything decorative lives here.
 */

export type MotifColour = "deco" | "ivory";

export type Motif = {
  icon: SeasonIconName;
  /** Centre, % of the box width */
  x: number;
  /** Centre, % of the box height */
  y: number;
  size: number;
  rotate: number;
  colour: MotifColour;
  opacity: number;
};

/** A thread from the top edge with icons stacked down it. */
export type Hanger = {
  x: number;
  /** Thread length in px before the first item */
  thread: number;
  items: SeasonIconName[];
  size: number;
  colour: MotifColour;
  opacity: number;
};

/** One icon repeated along an edge. */
export type Band = {
  icon: SeasonIconName;
  size: number;
  count: number;
  colour: MotifColour;
  opacity: number;
};

export type SurfaceArtwork = {
  hero: Motif | null;
  scatter: Motif[];
  hangers: Hanger[];
  band: Band;
};

export type ThemeArtwork = {
  /** Second colour for motifs on the accent, upper-case `#RRGGBB` */
  deco: string;
  /** Icons for the header scatter, cycled over the slots */
  headerIcons: SeasonIconName[];
  /** Small icon that fills the leftover header slots */
  headerFiller: SeasonIconName;
  tag: SurfaceArtwork;
  footer: SurfaceArtwork;
};

/** Header scatter slots: [x %, y %, size px, rotation °] over the top row. */
export type HeaderSlot = readonly [x: number, y: number, size: number, rotate: number];

